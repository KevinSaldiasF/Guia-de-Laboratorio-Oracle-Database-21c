--COMUNA
CREATE TABLE comuna (
    id_comuna NUMBER
        GENERATED BY DEFAULT AS IDENTITY ( START WITH 100 INCREMENT BY 1 ),
    nombre_comuna VARCHAR2 (100) NOT NULL,
    CONSTRAINT pk_comuna PRIMARY KEY ( id_comuna ),
    CONSTRAINT uk_comuna UNIQUE ( nombre_comuna )
);
-- CIUDADANO
CREATE TABLE CIUDADANO (
    ID_CIUDADANO NUMBER GENERATED BY DEFAULT AS IDENTITY
    (START WITH 9000 INCREMENT BY 10),
    rut VARCHAR2(12) NOT NULL,
    nombre VARCHAR2(100) NOT NULL,
    edad NUMBER NOT NULL,
    genero VARCHAR2(1) NOT NULL,
    fecha_registro DATE DEFAULT sysdate,
    usuario_creacion VARCHAR2(50) DEFAULT user,
    id_comuna NUMBER NOT NULL,
    constraint pk_ciudadano PRIMARY KEY (id_ciudadano),
    constraint uk_ciudadano_rut UNIQUE (rut),
    constraint ck_edad CHECK(edad > 17),
    constraint fk_ciudadano_comuna FOREIGN KEY(id_comuna)
        REFERENCES comuna (id_comuna)
);

