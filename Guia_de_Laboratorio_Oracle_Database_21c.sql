    COUNT(CASE WHEN c.edad BETWEEN 18 AND 23 THEN 1 END) AS "18-23",
    COUNT(CASE WHEN c.edad BETWEEN 24 AND 35 THEN 1 END) AS "24-35",
    COUNT(CASE WHEN c.edad BETWEEN 36 AND 50 THEN 1 END) AS "36-50",
    COUNT(CASE WHEN c.edad >= 51 THEN 1 END) AS "51+",
    COUNT(c.id_ciudadano) AS total_ciudadanos
FROM comuna co
INNER JOIN ciudadano c 
    ON co.id_comuna = c.id_comuna
GROUP BY co.nombre_comuna
HAVING COUNT(c.id_ciudadano) > 5
ORDER BY total_ciudadanos DESC;


